# C3: PWA (service worker reale, server locale su copia temporanea del progetto). Installazione, pulizia cache, aggiornamento, offline, ritorno online, dati protetti.
import json,re,subprocess,os,sys,tempfile,shutil,socket,time
ROOT=os.environ.get('TVA_ROOT') or os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PW=tempfile.mkdtemp(prefix='tva_pwa_')   # copia di lavoro: il test sostituisce index.html/sw.js per simulare un aggiornamento
for f in ('index.html','sw.js'): shutil.copy(os.path.join(ROOT,f),os.path.join(PW,f))
os.symlink(os.path.join(ROOT,'assets'),os.path.join(PW,'assets'))
_s=socket.socket(); _s.bind(('127.0.0.1',0)); PORT=_s.getsockname()[1]; _s.close()
SRV=subprocess.Popen([sys.executable,'-m','http.server',str(PORT),'--bind','127.0.0.1','--directory',PW],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL); time.sleep(1.2)
from playwright.sync_api import sync_playwright
U='http://127.0.0.1:%d/index.html'%PORT
fails=[]
def ck(c,m,i=''):
    print(('PASS ' if c else 'FAIL ')+m,'' if c else i)
    if not c: fails.append(m)
BUILD=re.search(r'name="tva-build" content="([^"]+)"',open(''+PW+'/index.html').read()).group(1)
with sync_playwright() as p:
    b=p.chromium.launch(); cx=b.new_context(viewport={'width':390,'height':844}); pg=cx.new_page()
    errs=[]; pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.goto(U); pg.wait_for_timeout(800)
    # cache "vecchia" della stessa app e cache di un'altra app (non deve essere toccata)
    pg.evaluate("""async()=>{for(const n of ['marvel-timeline-cache-v9','altra-app-cache']){const c=await caches.open(n);await c.put('/x-'+n,new Response('x'))}}""")
    pg.evaluate("()=>{localStorage.setItem('marvelGuideCustomTimelineOrder','[3,1,2]');localStorage.setItem('marvelGuideActiveTimelineMode','custom');localStorage.setItem('marvel-ultimate-timeline-ratings',JSON.stringify({'001':4.5}));localStorage.setItem('marvel-ultimate-timeline-watched',JSON.stringify({'001':true,'002':true}))}")
    snap=lambda: pg.evaluate("()=>{const o={};['marvelGuideCustomTimelineOrder','marvelGuideActiveTimelineMode','marvel-ultimate-timeline-ratings','marvel-ultimate-timeline-watched'].forEach(k=>o[k]=localStorage.getItem(k));return JSON.stringify(o)}")
    before=snap()
    pg.evaluate("async()=>{const r=await navigator.serviceWorker.register('./sw.js');await navigator.serviceWorker.ready}") ; pg.wait_for_timeout(2500)
    pg.reload(); pg.wait_for_timeout(1500)
    sw=pg.evaluate("""async()=>{const r=await navigator.serviceWorker.getRegistration();const k=await caches.keys();return {ctl:!!navigator.serviceWorker.controller,act:r&&r.active&&r.active.state,keys:k}}""")
    ck(sw['ctl'] and sw['act']=='activated','installazione: SW attivo e pagina controllata',sw)
    ck(sw['keys'].count('marvel-timeline-cache-'+BUILD)==1,'cache nominata con la build corrente',sw['keys'])
    ck('altra-app-cache' in sw['keys'],'cache di altra origine/app NON toccata',sw['keys'])
    ver=pg.evaluate("""()=>new Promise(res=>{const mc=new MessageChannel();mc.port1.onmessage=e=>res(e.data);navigator.serviceWorker.controller.postMessage({type:'tva-get-version'},[mc.port2])})""")
    ck(ver['swBuild']==BUILD and ver['cache'].endswith(BUILD),'SW dichiara la build della pagina',ver)
    has=pg.evaluate("""async()=>{const c=await caches.open('marvel-timeline-cache-%s');const ks=(await c.keys()).map(r=>new URL(r.url).pathname);return ks}""" % BUILD)
    ck(any(k.endswith('/index.html') for k in has) and any(k=='/' for k in has),'pagina in precache (avvio offline subito dopo l\'installazione)',has[:6])
    d=lambda a,b2:{k:(json.loads(a).get(k),json.loads(b2).get(k)) for k in set(json.loads(a))|set(json.loads(b2)) if json.loads(a).get(k)!=json.loads(b2).get(k)}
    ck(snap()==before,'dati utente invariati dopo installazione',d(before,snap()))
    # offline
    cx.set_offline(True); pg.reload(); pg.wait_for_timeout(1500)
    t=pg.evaluate("()=>({title:document.title,ok:!!document.getElementById('homeHub')||!!document.querySelector('.card-wrap'),b:document.querySelector('meta[name=tva-build]').content})")
    ck(t['ok'] and t['b']==BUILD,'offline: la guida si apre dalla cache',t)
    ck(snap()==before,'offline: dati utente invariati')
    cx.set_offline(False)
    # nuova build servita (aggiornamento)
    NEW=BUILD+'x'
    h=open(''+PW+'/index.html').read().replace(BUILD,NEW); open(''+PW+'/index.html','w').write(h)
    s=open(''+PW+'/sw.js').read().replace(BUILD,NEW); open(''+PW+'/sw.js','w').write(s)
    pg.evaluate("async()=>{const r=await navigator.serviceWorker.getRegistration();await r.update()}"); pg.wait_for_timeout(3000)
    pg.reload(); pg.wait_for_timeout(3500)
    st=pg.evaluate("""async()=>({b:document.querySelector('meta[name=tva-build]').content,keys:await caches.keys()})""")
    ck(st['b']==NEW,'aggiornamento: la pagina in esecuzione e\' la nuova build',st['b'])
    ck(st['keys'].count('marvel-timeline-cache-'+NEW)==1 and ('marvel-timeline-cache-'+BUILD) not in st['keys'],'aggiornamento: cache vecchia rimossa, nuova presente',st['keys'])
    ck('altra-app-cache' in st['keys'],'aggiornamento: cache di altra app ancora presente')
    ck('marvel-timeline-cache-v9' not in st['keys'],'aggiornamento: cache obsoleta v9 della stessa app rimossa',st['keys'])
    ck(snap()==before,'aggiornamento: ordine, modalita\', voti e progressi invariati')
    # offline dopo l'aggiornamento, senza navigazioni intermedie
    cx.set_offline(True); pg.reload(); pg.wait_for_timeout(1500)
    t=pg.evaluate("()=>document.querySelector('meta[name=tva-build]').content")
    ck(t==NEW,'offline dopo aggiornamento: serve la build NUOVA (nessun file obsoleto)',t)
    cx.set_offline(False); pg.reload(); pg.wait_for_timeout(1500)
    ck(pg.evaluate("()=>document.querySelector('meta[name=tva-build]').content")==NEW,'ritorno online: nuova build')
    ck(not [e for e in errs if 'ERR' not in e],'nessun errore JS',errs[:2])
    b.close()
# --- C3b: deploy a meta' (sw.js di una build, index.html di un'altra): l'HTML di build diversa NON entra nella cache della nuova build
MIX=tempfile.mkdtemp(prefix='tva_mix_')
shutil.copy(os.path.join(ROOT,'sw.js'),MIX+'/sw.js'); os.symlink(os.path.join(ROOT,'assets'),MIX+'/assets')
cur=open(os.path.join(ROOT,'index.html')).read()
old=re.sub(r'(name="tva-build" content=")[^"]*',lambda m:m.group(1)+'20200101-0000-old',cur,count=1)
open(MIX+'/index.html','w').write(old)
_s=socket.socket(); _s.bind(('127.0.0.1',0)); P2=_s.getsockname()[1]; _s.close()
SRV2=subprocess.Popen([sys.executable,'-m','http.server',str(P2),'--bind','127.0.0.1','--directory',MIX],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL); time.sleep(1.2)
CJS="""async()=>{const k=(await caches.keys()).filter(x=>x.indexOf('marvel-timeline-cache-')===0);const out={keys:k,pages:[]};for(const n of k){const c=await caches.open(n);for(const u of ['./','./index.html']){const m=await c.match(u);if(m){const t=(await m.text()).slice(0,8192);const b=/name="tva-build" content="([^"]+)"/.exec(t);out.pages.push([n.slice(-12),u,b&&b[1]])}}}return out}"""
with sync_playwright() as p2:
    b2=p2.chromium.launch(); cx2=b2.new_context(); g=cx2.new_page()
    g.goto('http://127.0.0.1:%d/index.html'%P2); g.wait_for_timeout(800)
    g.evaluate("()=>{localStorage.setItem('marvelGuideCustomTimelineOrder','[2,1]')}")
    g.evaluate("async()=>{await navigator.serviceWorker.register('./sw.js');await navigator.serviceWorker.ready}"); g.wait_for_timeout(2500)
    r=g.evaluate(CJS)
    ck(len(r['keys'])==1 and r['keys'][0].endswith(BUILD),'deploy a meta\': cache della build nuova creata',r['keys'])
    ck(all(x[2]==BUILD for x in r['pages']),'deploy a meta\': nessun HTML di altra build nella cache nuova',r['pages'])
    ck(not r['pages'],'deploy a meta\': index non salvato (nessuna pagina in cache)',r['pages'])
    # deploy completato: index coerente -> al successivo avvio online il SW lo serve e lo mette in cache (network-first)
    open(MIX+'/index.html','w').write(cur)
    g.reload(); g.wait_for_timeout(2000)
    r=g.evaluate(CJS)
    ck(r['pages'] and all(x[2]==BUILD for x in r['pages']),'deploy completato: la build coerente entra in cache alla navigazione online',r['pages'])
    cx2.set_offline(True); g.reload(); g.wait_for_timeout(1500)
    ck(g.evaluate("()=>document.querySelector('meta[name=tva-build]').content")==BUILD,'dopo il deploy completo: offline serve la build corretta')
    ck(json.loads(g.evaluate("()=>localStorage.getItem('marvelGuideCustomTimelineOrder')"))==[2,1],'dati utente intatti nel caso deploy a meta\'')
    cx2.set_offline(False)
    b2.close()
SRV2.terminate(); shutil.rmtree(MIX,ignore_errors=True)
print('FAILS',len(fails),fails)
SRV.terminate(); shutil.rmtree(PW,ignore_errors=True)
